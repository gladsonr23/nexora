-- Nexora Vault — Supabase setup. Run once in: Supabase Dashboard → SQL Editor.

-- 1) Sequential, human-readable material IDs (MAT-001, MAT-002, …), generated
--    atomically by Postgres so two simultaneous uploads can never collide.
create sequence if not exists public.materials_material_seq;

create or replace function public.next_material_id()
returns text
language sql
as $$
  select 'MAT-' || case when n < 1000 then lpad(n::text, 3, '0') else n::text end
  from (select nextval('public.materials_material_seq') as n) s;
$$;

-- Only the backend (service role) may call it.
revoke all on function public.next_material_id() from public, anon, authenticated;
grant execute on function public.next_material_id() to service_role;

-- 2) Vault metadata. Column set = your suggested schema PLUS the two fields the
--    existing Vault UI already depends on (category, page_count).
create table if not exists public.materials (
  id                bigint generated by default as identity primary key,
  material_id       text unique not null,
  user_id           text not null,                 -- Clerk user ID (e.g. user_2abc…)
  filename          text not null,                 -- display name (maps to old original_filename)
  subject           text default 'General',
  category          text not null default 'Notes',
  description       text,
  page_count        integer not null default 0,
  storage_path      text not null,                 -- user_<clerkId>/<MATERIAL_ID>/file.pdf
  mime_type         text,
  file_size         bigint,                        -- maps to old file_size_bytes
  extracted_text    text,
  extraction_status text not null default 'pending',  -- extracting | complete | needs_ocr | failed
  indexing_status   text not null default 'pending',  -- pending | ready
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

create index if not exists materials_user_created_idx
  on public.materials (user_id, created_at desc);

-- 3) Defense in depth: RLS on with NO policies = the public anon key can read
--    nothing. The Express backend uses the service-role key, which bypasses RLS,
--    and scopes every query by user_id itself.
alter table public.materials enable row level security;

-- 4) Private Storage bucket for the PDFs (same as creating it in the dashboard).
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('vault', 'vault', false, 26214400, array['application/pdf'])
on conflict (id) do nothing;
-- storage.objects already has RLS enabled; with no policies, anon cannot touch it.
