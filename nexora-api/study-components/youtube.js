

function parseYouTubeUrl(value) {
  let url;
  try { url = new URL(String(value || '').trim()); } catch (_) { throw new Error('Paste a valid YouTube video link.'); }
  const host = url.hostname.toLowerCase();
  if (url.protocol !== 'https:' || !['youtube.com', 'www.youtube.com', 'm.youtube.com', 'youtu.be'].includes(host)) {
    throw new Error('Paste a valid HTTPS YouTube video link.');
  }
  const parts = url.pathname.split('/').filter(Boolean);
  const id = host === 'youtu.be' ? parts[0] : parts[0] === 'watch' ? url.searchParams.get('v') : ['shorts', 'live', 'embed'].includes(parts[0]) ? parts[1] : null;
  if (!/^[A-Za-z0-9_-]{11}$/.test(id || '')) throw new Error('The link must point to one YouTube video.');
  return {videoId: id, sourceUrl: `https://www.youtube.com/watch?v=${id}`};
}

function selectCaptionLanguage(languages) {
  if (!Array.isArray(languages) || !languages.length) return null;
  return languages.find(track => track.isAutoGenerated) ||
    languages.find(track => /^en(?:-|$)/i.test(track.languageCode || '')) || languages[0];
}

function formatTime(seconds) {
  const total = Math.max(0, Math.floor(Number(seconds) || 0));
  const hours = Math.floor(total / 3600);
  const minutes = Math.floor(total % 3600 / 60);
  const remainder = total % 60;
  return hours ? `${hours}:${String(minutes).padStart(2, '0')}:${String(remainder).padStart(2, '0')}` : `${String(minutes).padStart(2, '0')}:${String(remainder).padStart(2, '0')}`;
}

function formatCaptions(segments) {
  return (segments || []).map(segment => {
    const text = String(segment.text || '').replace(/\s+/g, ' ').trim();
    return text ? `[${formatTime(segment.offset)}] ${text}` : '';
  }).filter(Boolean).join('\n');
}

function isNetworkFailure(error) {
  if (!error) return false;
  if (/fetch failed|network|socket|connect/i.test(String(error.message || ''))) return true;
  if (['EACCES','ECONNREFUSED','ECONNRESET','ENETUNREACH','ETIMEDOUT'].includes(error.code)) return true;
  if (Array.isArray(error.errors) && error.errors.some(isNetworkFailure)) return true;
  return isNetworkFailure(error.cause);
}

function responseHasCaptionTracks(response) {
  return response.clone().json().then(playerJson => {
    const tracklist = playerJson.captions?.playerCaptionsTracklistRenderer || playerJson.playerCaptionsTracklistRenderer;
    return Array.isArray(tracklist?.captionTracks) && tracklist.captionTracks.length > 0;
  }).catch(() => false);
}

function createPlayerFetch(fetchImpl = (...args) => fetch(...args)) {
  return async params => {
    const primaryResponse = await fetchImpl(params.url, {
      method:params.method,
      headers:params.headers,
      body:params.body,
      signal:params.signal,
    });
    if (await responseHasCaptionTracks(primaryResponse)) return primaryResponse;

    let playerBody;
    try {
      playerBody = JSON.parse(params.body || '{}');
    } catch (_) {
      return primaryResponse;
    }
    playerBody.context = playerBody.context || {};
    playerBody.context.client = {
      ...(playerBody.context.client || {}),
      clientName:'IOS',
      clientVersion:'20.10.4',
    };
    try {
      const fallbackResponse = await fetchImpl(params.url, {
        method:params.method,
        headers:params.headers,
        body:JSON.stringify(playerBody),
        signal:params.signal,
      });
      if (await responseHasCaptionTracks(fallbackResponse)) return fallbackResponse;
      console.warn('[youtube-transcript] iOS player fallback also returned no caption tracks', {
        videoId:playerBody.videoId,
        primaryStatus:primaryResponse.status,
        fallbackStatus:fallbackResponse.status,
      });
    } catch (error) {
      console.warn('[youtube-transcript] iOS player fallback request failed', {
        videoId:playerBody.videoId,
        errorName:error?.name || 'Error',
        errorMessage:error?.message || 'Unknown error',
      });
    }
    return primaryResponse;
  };
}

async function fetchYouTubeLecture(value, options = {}) {
  const transcriptApi = options.transcriptApi || await import('youtube-transcript-plus');
  const listLanguagesImpl = options.listLanguagesImpl || transcriptApi.listLanguages;
  const fetchTranscriptImpl = options.fetchTranscriptImpl || transcriptApi.fetchTranscript;
  const transcriptConfig = options.transcriptApi ? {} : {
    playerFetch:options.playerFetch || createPlayerFetch(options.fetchImpl),
  };
  const {videoId, sourceUrl} = parseYouTubeUrl(value);
  try {
    let languages = [];
    try {
      languages = await listLanguagesImpl(videoId, transcriptConfig);
    } catch (error) {
      const canTryDirectTranscript =
        error instanceof transcriptApi.YoutubeTranscriptNotAvailableError ||
        error instanceof transcriptApi.YoutubeTranscriptNotAvailableLanguageError ||
        error instanceof transcriptApi.YoutubeTranscriptDisabledError;
      if (!canTryDirectTranscript) throw error;
      console.warn('[youtube-transcript] language discovery failed; trying direct transcript retrieval', {
        videoId,
        errorName:error?.name || 'Error',
      });
    }
    const selected = selectCaptionLanguage(languages);
    // YouTube sometimes exposes captions in the player but omits them from
    // the language-list response. Try the transcript endpoint without a
    // language hint before concluding that no captions are available.
    const transcriptOptions = {videoDetails:true, retries:2};
    if (selected) transcriptOptions.lang = selected.languageCode;
    let result;
    try {
      result = await fetchTranscriptImpl(videoId, {...transcriptOptions, ...transcriptConfig});
    } catch (error) {
      const canRetryWithoutLanguage = selected && (
        error instanceof transcriptApi.YoutubeTranscriptNotAvailableError ||
        error instanceof transcriptApi.YoutubeTranscriptNotAvailableLanguageError
      );
      if (!canRetryWithoutLanguage) throw error;
      result = await fetchTranscriptImpl(videoId, {videoDetails:true, retries:2, ...transcriptConfig});
    }
    const captions = formatCaptions(result.segments);
    if (captions.length < 300) throw new Error('This video has too little caption text to create reliable study notes.');
    if (captions.length > 240_000) throw new Error('This lecture is too long for one set of notes. Try a shorter video.');
    const title = String(result.videoDetails?.title || '').trim();
    if (!title) throw new Error('Could not read the lecture title from YouTube.');
    const languageCode = result.segments?.[0]?.lang || selected?.languageCode || 'unknown';
    return {videoId, sourceUrl, title:title.slice(0, 200), captions, languageCode,
      languageWarning:!/^en(?:-|$)/i.test(languageCode)};
  } catch (error) {
    console.warn('[youtube-transcript] caption retrieval failed', {
      videoId,
      errorName:error?.name || 'Error',
      errorMessage:error?.message || 'Unknown error',
    });
    if (error instanceof transcriptApi.YoutubeTranscriptDisabledError) throw new Error('YouTube reports that captions are disabled for this video.');
    if (error instanceof transcriptApi.YoutubeTranscriptNotAvailableError || error instanceof transcriptApi.YoutubeTranscriptNotAvailableLanguageError) {
      throw new Error('YouTube did not return transcript data to Nexora. Captions may still be visible in the player; try again shortly.');
    }
    if (error instanceof transcriptApi.YoutubeTranscriptVideoUnavailableError) throw new Error('This YouTube video is unavailable or private.');
    if (isNetworkFailure(error)) {
      throw new Error('Nexora could not reach YouTube. Check the internet connection and allow the local server network access, then try again.', {cause:error});
    }
    throw error;
  }
}

module.exports = { parseYouTubeUrl, selectCaptionLanguage, formatCaptions, createPlayerFetch, fetchYouTubeLecture };

